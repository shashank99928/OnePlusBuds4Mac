#!/bin/bash
# Regenerates Sources/BudsBarKit/FixtureCorpus.swift from Tests/Fixtures/buds4-frames.hex.
#
# Fixtures are captured, not written. This script is the only thing allowed to put bytes
# into the corpus, and a test asserts the two files agree byte for byte — so a fixture whose
# `len` varint disagrees with its own payload-length field cannot be introduced by hand.
#
# To re-capture: connect the buds, then
#     BUDSBAR_TRACE=1 BUDSBAR_HARVEST=1 "./OnePlus Buds 4.app/Contents/MacOS/OnePlusBuds4"
# and keep the `RX <hex>   |   <decode>` lines. Harvesting runs a fixed mode/level/EQ/
# BassWave sweep and restores what it found, so the capture covers every frame type.
set -euo pipefail
cd "$(dirname "$0")/.."

python3 - <<'PY'
import pathlib

hex_file = pathlib.Path("Tests/Fixtures/buds4-frames.hex")
swift_file = pathlib.Path("Sources/BudsBarKit/FixtureCorpus.swift")

entries = []
comments = []          # the comment block immediately above the current line
seen_entry = False     # everything before the first entry is the file header, not a note
for line in hex_file.read_text().splitlines():
    if line.startswith("#"):
        text = line.lstrip("#").strip()
        if text:
            comments.append(text)
        continue
    if "=" not in line:
        continue
    name, hexstr = line.split("=", 1)
    if not seen_entry:
        seen_entry = True
        comments = []
    entries.append((name.strip(), " ".join(hexstr.split()), comments))
    comments = []

out = []
out.append("// Generated by Tools/freeze-fixtures.sh from Tests/Fixtures/buds4-frames.hex.")
out.append("// Do not edit by hand: run the script. A test asserts this file and the .hex")
out.append("// record agree byte for byte.")
out.append("")
out.append("import Foundation")
out.append("")
out.append("/// Raw RFCOMM frames captured from a OnePlus Buds 4 on the `oppointeraction` channel.")
out.append("///")
out.append("/// This is the rawest material the project has: the bytes as they came off the wire,")
out.append("/// with both length fields intact. Every parse check in `BudsProtocol.selfCheck()` and")
out.append("/// in the test suite runs against these, never against a reconstruction — the one time")
out.append("/// a fixture was typed out by hand its `len` varint disagreed with its payload length,")
out.append("/// which is a malformed frame, and the check that consumed it trapped.")
out.append("public enum FixtureCorpus {")
out.append("    /// One captured frame.")
out.append("    public struct Capture {")
out.append("        public let name: String")
out.append("        /// Why this frame is in the corpus, in one line.")
out.append("        public let note: String")
out.append("        public let hex: String")
out.append("")
out.append("        public var bytes: [UInt8] {")
out.append("            hex.split(separator: \" \").compactMap { UInt8($0, radix: 16) }")
out.append("        }")
out.append("    }")
out.append("")
out.append("    /// Every capture in `Tests/Fixtures/buds4-frames.hex`, in file order.")
out.append("    public static let frames: [Capture] = [")
for name, hexstr, notes in entries:
    note = " ".join(notes).replace('"', "'")
    out.append("        Capture(name: \"%s\"," % name)
    out.append("                note: \"%s\"," % note)
    out.append("                hex: \"%s\")," % hexstr)
out.append("    ]")
out.append("}")
swift_file.write_text("\n".join(out) + "\n")
print("wrote %s (%d captures)" % (swift_file, len(entries)))
PY
